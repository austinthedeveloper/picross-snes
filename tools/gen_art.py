#!/usr/bin/env python3
"""Turns data/art/ (tools/import_art.py) into SNES tiles (ADR-010).

Called by gen_assets.py. For each image it writes assets/generated/
art_<group>_<id>.bin: a 32-byte palette (16 BGR555 colours, colour 0 the
transparent one) and then the image's 4bpp tiles, row by row, left to right
(64x64: 8 rows of 8 tiles). Each is its own ROM section, and art.h gives C a
pointer table per group in the order tools/gen_story.py numbers them
(sorted by id): ART_CAST_INIT(a), ART_ENEMIES_INIT(a), ...
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "data" / "art"
GROUPS = ["cast", "enemies", "gadgets", "icons"]


def read_art(path):
    lines = path.read_text(encoding="utf-8").split("\n")
    w, h = (int(v) for v in lines[0].split()[1:3])
    palette = []
    i = 1
    while lines[i].startswith("#"):
        palette.append(int(lines[i][1:], 16))
        i += 1
    rows = [line for line in lines[i + 1:i + 1 + h]]
    assert len(rows) == h and all(len(r) == w for r in rows), path
    pixels = [["0123456789abcdef".index(ch) if ch != "." else 0 for ch in r] for r in rows]
    return w, h, palette, pixels


def bgr555(rgb):
    r, g, b = (rgb >> 16) & 0xFF, (rgb >> 8) & 0xFF, rgb & 0xFF
    return (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)


def tile_4bpp(pixels, x0, y0):
    out = bytearray(32)
    for y in range(8):
        for x in range(8):
            v = pixels[y0 + y][x0 + x]
            bit = 7 - x
            for plane in range(4):
                if v & (1 << plane):
                    out[(plane >> 1) * 16 + y * 2 + (plane & 1)] |= 1 << bit
    return bytes(out)


def ident(group, name):
    return f"art_{group}_{name}".replace("-", "_")


def build():
    """Returns ({bin name: bytes}, art.h text)."""
    bins = {}
    h = ["/* Generated by tools/gen_art.py. Include once (art.c). */"]
    for group in GROUPS:
        names = sorted(p.stem for p in (ART / group).glob("*.txt"))
        for name in names:
            w, h_, palette, pixels = read_art(ART / group / f"{name}.txt")
            assert w % 8 == 0 and h_ % 8 == 0, f"{group}/{name}: size {w}x{h_}"
            assert len(palette) <= 15
            data = bytearray(2)  # colour 0: transparent
            for rgb in palette:
                c = bgr555(rgb)
                data += bytes((c & 0xFF, c >> 8))
            data += bytes(32 - len(data))
            for ty in range(0, h_, 8):
                for tx in range(0, w, 8):
                    data += tile_4bpp(pixels, tx, ty)
            bins[ident(group, name)] = bytes(data)
            h.append(f"ROM_DECLARE({ident(group, name)});")
        key = group.upper()
        h.append(f"#define ART_{key}_COUNT {len(names)}")
        h.append(f"#define ART_{key}_INIT(a) do {{ "
                 + " ".join(f"(a)[{i}] = ROM_DATA({ident(group, n)});" for i, n in enumerate(names))
                 + " } while (0)")
    return bins, "\n".join(h) + "\n"


def asm(bins):
    out = ["; Generated by tools/gen_art.py. Do not edit."]
    for name in bins:
        out += [f'.section ".rodata_{name}" superfree', f"{name}_bin:",
                f'.incbin "assets/generated/{name}.bin"', ".ends", ""]
    return "\n".join(out) + "\n"
